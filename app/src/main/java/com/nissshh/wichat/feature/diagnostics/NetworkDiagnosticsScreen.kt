@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun NetworkDiagnosticsScreen(
    repository: WiChatRepository,
    onBackPress: () -> Unit
) {
    val diagnostics by repository.networkDiagnostics.collectAsState()

    Surface(
        modifier = Modifier.fillMaxSize(),
        color = MaterialTheme.colorScheme.background
    ) {
        Column(modifier = Modifier.fillMaxSize()) {
            TopAppBar(
                title = {
                    Text(
                        text = "Network Diagnostics",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.SemiBold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onBackPress) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back",
                            tint = MaterialTheme.colorScheme.onSurface
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surface
                )
            )

            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)
            ) {
                // Status Items
                DiagnosticItemCard(
                    title = "Wi-Fi LAN Connection",
                    value = if (diagnostics.isWifiConnected) "Connected to local Wi-Fi" else "Not connected to Wi-Fi",
                    isGood = diagnostics.isWifiConnected,
                    icon = Icons.Default.Wifi
                )

                DiagnosticItemCard(
                    title = "Network Service Discovery (mDNS)",
                    value = if (diagnostics.isScanningActive) "Active (_wichat._tcp)" else "Ready / Idle",
                    isGood = true,
                    icon = Icons.Default.Router
                )

                DiagnosticItemCard(
                    title = "Active Local TCP Port",
                    value = "Port ${diagnostics.activePort} (Bound to 0.0.0.0)",
                    isGood = diagnostics.activePort > 0,
                    icon = Icons.Default.CheckCircle
                )

                DiagnosticItemCard(
                    title = "Discovered WiChat Peers",
                    value = "${diagnostics.discoveredPeerCount} peers reachable on LAN",
                    isGood = diagnostics.discoveredPeerCount > 0,
                    icon = Icons.Default.Info
                )

                Spacer(modifier = Modifier.height(10.dp))

                // Router Isolation Advisory
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(16.dp),
                    colors = CardDefaults.cardColors(
                        containerColor = MaterialTheme.colorScheme.surfaceVariant
                    )
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(
                                imageVector = Icons.Default.Warning,
                                contentDescription = null,
                                tint = MaterialTheme.colorScheme.primary
                            )
                            Spacer(modifier = Modifier.width(10.dp))
                            Text(
                                text = "About AP / Client Isolation",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.SemiBold,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                        }

                        Spacer(modifier = Modifier.height(8.dp))

                        Text(
                            text = "Some public, university, or guest Wi-Fi networks have Client Isolation (AP Isolation) enabled. This router setting blocks devices on the same Wi-Fi from talking to each other. If devices are on the same Wi-Fi but cannot find each other, try connecting both to a home Wi-Fi network or a phone's personal Wi-Fi hotspot.",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }
            }
        }
    }
}

@Composable
fun DiagnosticItemCard(
    title: String,
    value: String,
    isGood: Boolean,
    icon: ImageVector
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(14.dp),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surface
        ),
        border = androidx.compose.foundation.BorderStroke(
            1.dp,
            MaterialTheme.colorScheme.outline.copy(alpha = 0.4f)
        )
    ) {
        Row(
            modifier = Modifier.padding(14.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(42.dp)
                    .clip(CircleShape)
                    .background(
                        if (isGood) MaterialTheme.colorScheme.primaryContainer
                        else MaterialTheme.colorScheme.surfaceVariant
                    ),
                contentAlignment = Alignment.Center
            ) {
                Icon(
                    imageVector = icon,
                    contentDescription = null,
                    tint = if (isGood) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.error,
                    modifier = Modifier.size(22.dp)
                )
            }

            Spacer(modifier = Modifier.width(14.dp))

            Column {
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Text(
                    text = value,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }
    }
}
